"""Reference-value parity against R's ``drc`` package (plan sections 6.1, 6.2; Phase 4 plan).

Every expected number here is read from the JSON fixtures under ``tools/drc_reference/``,
generated by ``tools/drc_reference/generate.R`` inside the pinned ``rocker/r-ver:4.6.1``
container (see ``tools/drc_reference/README.md``). **This file never runs R and never needs R
installed** -- it reads only the committed JSON.

Tolerances: plan section 6.1 sets ``1e-4`` relative on parameters and log-likelihood, and
``1e-3`` relative on interval endpoints (the latter not exercised yet -- ``ED``/``EDcomp``/
profile parity are Phase 5/6 fixtures, read by later test-author work, not by this file). It
says nothing about covariance. ``decisions/0007``'s "Reference tolerances for covariance"
amendment sets covariance parity against drc's ``vcov`` at ``1e-3`` relative, because drc's
``vcov`` comes from a finite-difference Hessian inside its own optimizer (about ``1.3e-4`` away
from an independent numerical Hessian on finney71, per ``finney71.json``'s
``observed_hessian_check``) -- not the ordinary ``1e-4`` parameter bound. The internal
consistency check between the GLM path and the likelihood path
(``TestGlmPathMatchesLikelihoodPathNearBoundary``) has no such excuse and is held at the full
``1e-4``.

A failing test here is a reference-value drift: the fixed-asymptote GLM path this exercises is
the one part of Phase 4 with an independent, non-robustmargin implementation to check against. Per
``CLAUDE.md``, that failure is a finding, never resolved by loosening the tolerance or adjusting
the expected value.
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any

import numpy as np
import pytest

from robustmargin import Axis, Observations, Status, fit_dose_response

_FIXTURE_DIR = Path(__file__).resolve().parents[2] / "tools" / "drc_reference"
_REL_TOL_PARAMS = 1e-4
# decisions/0007's "Reference tolerances for covariance" amendment: covariance against drc's
# LN.2/LL.2 vcov is compared at 1e-3 relative, not the ordinary 1e-4 parameter tolerance --
# drc's vcov comes from a numerical Hessian inside its own optimizer and sits about 1.3e-4 away
# from an independent numerical Hessian even on drc's own coefficients (finney71.json's
# observed_hessian_check), so 1e-4 is not attainable against drc itself.
_REL_TOL_COV = 1e-3
# The internal consistency check between the GLM path and the GenericLikelihoodModel path (on
# the same data, with the likelihood path's asymptotes pinned a hair inside (0, 1)) has no such
# excuse -- both sides are robustmargin's own computation of the same quantity -- and is held at
# the ordinary 1e-4 (decisions/0007's amendment).
_REL_TOL_PATH_CONSISTENCY = 1e-4


def _load(name: str) -> dict[str, Any]:
    with (_FIXTURE_DIR / name).open() as fh:
        result: dict[str, Any] = json.load(fh)
    return result


def _matrix(fixture_block: dict[str, Any]) -> np.ndarray:
    return np.array(fixture_block["values"], dtype=float)


def _finney71_observations(axis_scale: str = "log") -> Observations:
    fixture = _load("finney71.json")
    dose = fixture["dataset"]["dose"]
    total = fixture["dataset"]["total"]
    affected = fixture["dataset"]["affected"]
    # robustmargin tracks SUCCESS; finney71's "affected" plays the role of failure (fixture note,
    # and the Phase 4 plan's "Mapping into robustmargin" section), so successes = total - affected.
    successes = [t - a for t, a in zip(total, affected, strict=True)]
    axis = Axis(name="dose", unit="unit", scale=axis_scale)
    return Observations.from_counts(
        axis,
        severity=dose,
        successes=successes,
        trials=total,
        outcome="success",
        direction="decreasing",
    )


def _delta_transform_drc_be_covariance(
    b: float, e: float, *, s_sign: float, sigma_be: np.ndarray
) -> np.ndarray:
    """The natural-scale ``(mu, s)`` covariance from drc's own ``(b, e)`` covariance via the
    delta method (decisions/0007: the covariance parity reference is drc's ``vcov``, not
    ``glm``'s expected-information ``cov_params()``).

    ``mu = log(e)`` always. ``s = s_sign / b``, where ``s_sign`` is ``+1`` for ``LN.2`` (whose
    ``b`` comes out positive on finney71) or ``-1`` for ``LL.2`` (whose ``b`` comes out
    negative) -- see ``tools/drc_reference/README.md``'s sign-convention note, empirically
    confirmed against ``predict()`` there, not assumed here. Jacobian, rows ``(mu, s)``,
    columns ``(b, e)``: ``d(mu)/d(b) = 0``, ``d(mu)/d(e) = 1/e``; ``d(s)/d(b) =
    -s_sign/b**2``, ``d(s)/d(e) = 0``.
    """
    jacobian = np.array(
        [
            [0.0, 1.0 / e],
            [-s_sign / b**2, 0.0],
        ]
    )
    return jacobian @ sigma_be @ jacobian.T


def _covariance_entry(fit_covariance: Any, name_a: str, name_b: str) -> float:
    i = fit_covariance.names.index(name_a)
    j = fit_covariance.names.index(name_b)
    return float(fit_covariance.matrix[i][j])


class TestFinney71Probit:
    """finney71, probit link, fixed ``upper=1.0, lower=0.0`` -- the GLM path (plan section
    5.1), against drc's ``LN.2`` and the independent ``glm`` fit, both in ``finney71.json``.
    """

    def test_mu_and_s_match_the_glm_and_drc_ln2_derivation(self) -> None:
        fixture = _load("finney71.json")
        glm = fixture["glm"]["probit"]
        beta0 = glm["coef"]["(Intercept)"]
        beta1 = glm["coef"]["log(dose)"]
        # Sign convention confirmed against predict() in generate.R (see finney71.json's
        # "mapping" block and tools/drc_reference/README.md): on finney71 (response=failure,
        # increasing with dose), LN.2's b comes out positive and mu=log(e), s=1/b.
        ln2 = fixture["drc"]["LN2"]
        assert ln2["coef"]["b:(Intercept)"] > 0.0
        expected_mu = -beta0 / beta1
        expected_s = 1.0 / beta1
        assert expected_mu == pytest.approx(
            math.log(ln2["coef"]["e:(Intercept)"]), rel=_REL_TOL_PARAMS
        )
        assert expected_s == pytest.approx(1.0 / ln2["coef"]["b:(Intercept)"], rel=_REL_TOL_PARAMS)

        obs = _finney71_observations()
        fit = fit_dose_response(obs, model="binomial", link="probit", upper=1.0, lower=0.0)

        assert fit.status is Status.OK
        assert fit.params is not None
        assert fit.params["mu"].value == pytest.approx(expected_mu, rel=_REL_TOL_PARAMS)
        assert fit.params["s"].value == pytest.approx(expected_s, rel=_REL_TOL_PARAMS)

    def test_mu_matches_mass_dose_p_ed50(self) -> None:
        """MASS ``dose.p`` at ``p=0.5``: an independent second source for the ED50, on the
        log(dose) scale directly (see finney71.json's ``mass_dose_p`` note: dose.p applies no
        inverse transform for a transformed covariate, so its "Dose" output is already ``mu``).
        """
        fixture = _load("finney71.json")
        expected_mu = fixture["mass_dose_p"]["dose"]

        obs = _finney71_observations()
        fit = fit_dose_response(obs, model="binomial", link="probit", upper=1.0, lower=0.0)

        assert fit.params is not None
        assert fit.params["mu"].value == pytest.approx(expected_mu, rel=_REL_TOL_PARAMS)

    def test_log_likelihood_matches_drc_and_glm(self) -> None:
        fixture = _load("finney71.json")
        expected = fixture["drc"]["LN2"]["logLik"]
        assert fixture["glm"]["probit"]["logLik"] == pytest.approx(expected, rel=_REL_TOL_PARAMS)

        obs = _finney71_observations()
        fit = fit_dose_response(obs, model="binomial", link="probit", upper=1.0, lower=0.0)

        assert fit.log_likelihood == pytest.approx(expected, rel=_REL_TOL_PARAMS)

    def test_covariance_matches_delta_transformed_drc_ln2_vcov(self) -> None:
        """decisions/0007: covariance parity is against drc's ``LN.2`` ``vcov`` (observed
        information), not ``glm``'s expected-information ``cov_params()``. ``finney71.json``'s
        ``drc.LN2.observed_hessian_check`` independently confirms drc's ``vcov`` really is the
        observed information here (matches an independently-computed numerical Hessian to
        within about 1e-6 relative on this dataset), so it is a trustworthy reference despite
        coming from drc's own numerical optimizer.
        """
        fixture = _load("finney71.json")
        ln2 = fixture["drc"]["LN2"]
        b = ln2["coef"]["b:(Intercept)"]
        e = ln2["coef"]["e:(Intercept)"]
        sigma_be = _matrix(ln2["vcov"])
        expected_cov = _delta_transform_drc_be_covariance(b, e, s_sign=1.0, sigma_be=sigma_be)

        obs = _finney71_observations()
        fit = fit_dose_response(obs, model="binomial", link="probit", upper=1.0, lower=0.0)

        assert fit.covariance is not None
        assert set(fit.covariance.names) == {"mu", "s"}
        assert _covariance_entry(fit.covariance, "mu", "mu") == pytest.approx(
            expected_cov[0, 0], rel=_REL_TOL_COV
        )
        assert _covariance_entry(fit.covariance, "s", "s") == pytest.approx(
            expected_cov[1, 1], rel=_REL_TOL_COV
        )
        assert _covariance_entry(fit.covariance, "mu", "s") == pytest.approx(
            expected_cov[0, 1], rel=_REL_TOL_COV
        )


