class TestGlmPathMatchesLikelihoodPathNearBoundary:
    """decisions/0007's path-consistency lock-in: a ``u=1, l=0`` fit (the GLM special case,
    decisions/0004) and the same data fit with ``upper``/``lower`` pinned a hair inside
    ``(0, 1)`` (``upper=1-1e-7, lower=1e-7`` -- not exactly ``1.0``/``0.0``, so this takes
    the ``GenericLikelihoodModel`` path, and pinned close enough to the boundary that the two
    curves are, for this purpose, the same curve) should report the same ``(mu, s)``
    covariance, since both sides are robustmargin's own computation of the same quantity. Held at
    the full ``1e-4`` relative (decisions/0007's amendment), not a looser path-consistency
    allowance: this checks internal agreement, not parity against drc, so there is no excuse
    for a wider tolerance. Do not widen this if it fails; report the actual gap instead.

    Why ``1e-7`` and not closer: at ``1e-12`` the likelihood's ``log(1 - P)`` terms lose about
    ``1e-4`` relative precision, so Newton's ``1e-10`` step tolerance sits inside float noise and
    convergence became CPU-dependent (one CI runner reported ``NOT_CONVERGED`` on code that
    passed elsewhere). Measured on macOS and on Linux at the dependency floor, ``1e-7`` gives
    path agreement of about ``1e-6`` -- 100x inside the tolerance -- with no such sensitivity.
    """

    def test_covariance_matches_between_the_two_fitting_paths(self) -> None:
        obs = _finney71_observations()

        fit_glm_path = fit_dose_response(obs, model="binomial", link="probit", upper=1.0, lower=0.0)
        fit_likelihood_path = fit_dose_response(
            obs, model="binomial", link="probit", upper=1.0 - 1e-7, lower=1e-7
        )

        assert fit_glm_path.status is Status.OK
        assert fit_likelihood_path.status is Status.OK
        assert fit_glm_path.covariance is not None
        assert fit_likelihood_path.covariance is not None
        assert set(fit_likelihood_path.covariance.names) == {"mu", "s"}

        for name_a, name_b in (("mu", "mu"), ("s", "s"), ("mu", "s")):
            glm_value = _covariance_entry(fit_glm_path.covariance, name_a, name_b)
            likelihood_value = _covariance_entry(fit_likelihood_path.covariance, name_a, name_b)
            assert likelihood_value == pytest.approx(glm_value, rel=_REL_TOL_PATH_CONSISTENCY)


class TestEstimatedAsymptoteParity:
    """The seeded simulated dataset in ``estimated_asymptotes.json``, fit with robustmargin's
    ``GenericLikelihoodModel`` path (D7 / ``decisions/0004``) and compared to drc's binomial
    ``LN.3`` (``upper="estimate", lower=0.0``) and ``LN.4`` (``upper="estimate",
    lower="estimate"``).

    **This class does not use plan section 6.1's usual 1e-4 relative bound, and that is
    recorded here and in ``tools/drc_reference/README.md``, not silently loosened.** drc's
    *default* fit (``drmc()``'s ``relTol=1e-7``) is under-converged on this dataset: refitting
    from the default fit's own coefficients with ``drmc(relTol=1e-14, maxIt=10000,
    method="BFGS")`` (the fixture's ``"tight"`` block, which is what this class reads --
    never ``"default"``) raises drc's own log-likelihood further, and robustmargin's
    ``GenericLikelihoodModel`` path reaches a log-likelihood at or above even that tight
    refit's. Comparing coefficients at 1e-4 relative against an optimizer that has not itself
    converged to that precision would be comparing against noise, not against a reference
    value, so:

    - (a) log-likelihood is checked as an inequality, ``robustmargin >= drc_tight - 1e-6``, not an
      equality band -- robustmargin is expected to do at least as well as drc's tight refit;
    - (b) ``mu`` is compared with an **absolute** tolerance of ``1e-4``, because the simulation's
      true ``mu`` is exactly ``0``, where a relative tolerance is ill-posed (dividing by ~0);
    - (c) ``s``, ``upper`` and ``lower`` are compared at a **relative 1e-3**, one order looser
      than the usual parameter bound, matching the precision the tight refit itself reached.

    No other tolerance in this file is affected: the fixed-asymptote GLM tests above still use
    the plan's ordinary 1e-4 relative bound, because that path has an exact, fully-converged
    drc/glm reference to compare against.
    """

    _LOGLIK_INEQUALITY_SLACK = 1e-6
    _ABS_TOL_MU = 1e-4
    _REL_TOL_LOOSE = 1e-3

    @staticmethod
    def _observations() -> tuple[Observations, dict[str, Any]]:
        fixture = _load("estimated_asymptotes.json")
        sim = fixture["simulation"]
        axis = Axis(name="severity", unit="unit", scale="log")
        obs = Observations.from_counts(
            axis,
            severity=sim["severity"],
            successes=sim["successes"],
            trials=sim["trials"],
            outcome="success",
            direction="decreasing",
        )
        return obs, fixture

    def test_upper_estimate_lower_fixed_matches_drc_ln3(self) -> None:
        obs, fixture = self._observations()
        ln3 = fixture["drc"]["LN3"]["tight"]
        # Sign convention confirmed against predict() in generate.R (README.md): fit on
        # successes (decreasing curve), b comes out negative, mu=log(e), s=-1/b, upper=d,
        # lower=0 (fixed by drc's own LN.3).
        assert ln3["coef"]["b:(Intercept)"] < 0.0
        expected_mu = math.log(ln3["coef"]["e:(Intercept)"])
        expected_s = -1.0 / ln3["coef"]["b:(Intercept)"]
        expected_upper = ln3["coef"]["d:(Intercept)"]

        fit = fit_dose_response(obs, model="binomial", link="probit", upper="estimate", lower=0.0)

        assert fit.status is Status.OK
        assert fit.params is not None
        assert fit.params["mu"].value == pytest.approx(expected_mu, abs=self._ABS_TOL_MU)
        assert fit.params["s"].value == pytest.approx(expected_s, rel=self._REL_TOL_LOOSE)
        assert fit.params["upper"].value == pytest.approx(expected_upper, rel=self._REL_TOL_LOOSE)
        assert fit.params["lower"].value == 0.0
        assert fit.params["lower"].fixed is True
        assert fit.log_likelihood is not None
        assert fit.log_likelihood >= ln3["logLik"] - self._LOGLIK_INEQUALITY_SLACK

    def test_upper_estimate_lower_estimate_matches_drc_ln4(self) -> None:
        obs, fixture = self._observations()
        ln4 = fixture["drc"]["LN4"]["tight"]
        assert ln4["coef"]["b:(Intercept)"] < 0.0
        expected_mu = math.log(ln4["coef"]["e:(Intercept)"])
        expected_s = -1.0 / ln4["coef"]["b:(Intercept)"]
        expected_upper = ln4["coef"]["d:(Intercept)"]
        expected_lower = ln4["coef"]["c:(Intercept)"]

        fit = fit_dose_response(
            obs, model="binomial", link="probit", upper="estimate", lower="estimate"
        )

        assert fit.status is Status.OK
        assert fit.params is not None
        assert fit.params["mu"].value == pytest.approx(expected_mu, abs=self._ABS_TOL_MU)
        assert fit.params["s"].value == pytest.approx(expected_s, rel=self._REL_TOL_LOOSE)
        assert fit.params["upper"].value == pytest.approx(expected_upper, rel=self._REL_TOL_LOOSE)
        assert fit.params["lower"].value == pytest.approx(expected_lower, rel=self._REL_TOL_LOOSE)
        assert fit.log_likelihood is not None
        assert fit.log_likelihood >= ln4["logLik"] - self._LOGLIK_INEQUALITY_SLACK
